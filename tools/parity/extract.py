"""One side's class surface, dumped as JSON.

Run as a CHILD PROCESS, one per side.  Both trees are packages named ``adcp``, so
importing both in one interpreter resolves one of them wrongly -- the import system
caches ``sys.modules['adcp']`` for whichever came first and every later
``from adcp.types... import`` silently reads that tree.  ``audit.py`` therefore spawns
this module twice with a different ``sys.path`` head each time and compares two JSON
documents, never two live class objects.

::

    python tools/parity/extract.py --src <tree>/src --package adcp.types._schemas --out ours.json
    python tools/parity/extract.py --src <tree>/src --package adcp.types.domains  --out theirs.json

**Provenance.**  Neither tree carries a per-NODE key on both sides.  Ours carries
``__adcp_schema__ = SchemaRef(document=..., pointer=...)`` on every emitted class.
``v9.2.0`` carries none -- grep finds no ``__adcp_schema__`` and no ``SchemaRef`` in its
whole ``src/adcp/types`` tree.  What it does carry is the ``# filename:`` line
datamodel-code-generator writes at the top of every module it emits, which is provenance
per MODULE (a document) and not per node.  So the match is document (from whichever key
the side carries) plus a DERIVED node identity, never a class name.

Fields of a record, and why each is there:

``module``/``name``
    where the class is DECLARED.  A class is attributed to the module whose
    ``__module__`` it names, so a re-export is not a second class.
``file``
    the declaring module's path relative to ``src/``.  This is what assigns the LAYER.
``header_document``
    the document named by the module's own generated header -- ``# filename:`` for
    datamodel-code-generator, ``Generated by codegen.emit from X`` for ours.
``schema_ref``
    ``__adcp_schema__``, document AND pointer.  Only our side has it.
``identity``
    the derived node identity the match runs on.  Enum: the member VALUE set (a renamed
    member is the same node, and our Â§4 rule collapsing two spellings of one identifier
    to a ``Literal`` means member NAMES cannot be the identity).  Model: the wire
    field-name set.  Root model: the shape of its root.
``fields``
    per field: required, the annotation as a string, and the values any ``Literal``
    pins.  The annotation string is not compared across sides -- two generators spell
    one type differently -- it is reported so a human reads the flagged difference.
``aliases``
    module-level names bound to something that is NOT a class.  Our Â§4 emits a root
    scalar as a module-level annotated alias and an enum on an untitled union branch as
    a ``Literal``, so a class-only census of our side would under-report what we
    represent.
"""

from __future__ import annotations

import argparse
import enum
import importlib
import json
import pkgutil
import re
import sys
import typing
from pathlib import Path

#: datamodel-code-generator's header, and ours.  Both name a document.
_HEADERS = (
    re.compile(r"^#\s+filename:\s+(\S+)", re.M),
    re.compile(r"^#\s*Generated by codegen\.emit from (\S+\.json)\b", re.M),
)


def _header_document(path: Path) -> str | None:
    try:
        head = path.read_text(encoding="utf-8")[:800]
    except OSError:
        return None
    for pattern in _HEADERS:
        found = pattern.search(head)
        if found is not None and found.group(1) != ".schema_temp":
            return found.group(1)
    return None


def _literal_values(annotation: object) -> list[str] | None:
    """Every value a ``Literal`` pins anywhere inside the annotation."""
    seen: list[object] = []

    def walk(node: object) -> None:
        if typing.get_origin(node) is typing.Literal:
            seen.extend(typing.get_args(node))
            return
        for arg in typing.get_args(node):
            walk(arg)

    walk(annotation)
    return sorted({str(v) for v in seen}) or None


def _annotation(node: object) -> str:
    text = str(node).replace("typing.", "").replace("adcp.types.", "")
    return re.sub(r"\s+", " ", text)[:600]


def _identity(record: dict[str, object]) -> list[object]:
    kind = record["kind"]
    if kind == "enum":
        return ["enum", sorted(str(v) for v in record["members"].values())]  # type: ignore[union-attr]
    if kind == "root":
        return ["root", record["root_shape"]]
    return ["model", sorted(record["fields"])]  # type: ignore[arg-type]


def _root_shape(annotation: object) -> str:
    """A generator-independent-ish summary of a root model's root.

    Two generators spell a list of X differently, so the shape keeps only the outer
    container and the Literal values, which are the parts both sides must agree on.
    """
    origin = typing.get_origin(annotation)
    container = getattr(origin, "__name__", None) or str(origin or "scalar")
    pins = _literal_values(annotation)
    return f"{container}|{','.join(pins) if pins else ''}"


def _modules(package: str) -> list[object]:
    root = importlib.import_module(package)
    out = [root]
    for info in pkgutil.walk_packages(root.__path__, prefix=package + "."):
        try:
            out.append(importlib.import_module(info.name))
        except Exception as exc:  # reported, never swallowed
            print(f"IMPORT-FAILED {info.name}: {exc!r}", file=sys.stderr)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", required=True)
    parser.add_argument("--package", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    src = Path(args.src).resolve()
    sys.path.insert(0, str(src))
    import pydantic

    classes: list[dict[str, object]] = []
    modules: list[dict[str, object]] = []

    for module in _modules(args.package):
        file = Path(getattr(module, "__file__", "") or "")
        try:
            relative = str(file.relative_to(src))
        except ValueError:
            relative = str(file)
        document = _header_document(src / relative) if relative else None
        aliases = {}
        for name, obj in vars(module).items():
            if name.startswith("__") or isinstance(obj, type):
                continue
            if type(obj).__module__.split(".")[0] in {"typing", "typing_extensions", "annotated_types"}:
                aliases[name] = _annotation(obj)
        modules.append(
            {
                "module": module.__name__,
                "file": relative,
                "header_document": document,
                "all": sorted(getattr(module, "__all__", ()) or ()),
                "aliases": aliases,
            }
        )
        for name, obj in vars(module).items():
            if not isinstance(obj, type) or getattr(obj, "__module__", None) != module.__name__:
                continue
            if issubclass(obj, enum.Enum) and obj is not enum.Enum:
                record: dict[str, object] = {
                    "kind": "enum",
                    "fields": {},
                    "members": {m.name: str(m.value) for m in obj},  # type: ignore[union-attr]
                }
            elif issubclass(obj, pydantic.BaseModel):
                if issubclass(obj, pydantic.RootModel):
                    root = obj.model_fields["root"]
                    record = {
                        "kind": "root",
                        "fields": {},
                        "root_annotation": _annotation(root.annotation),
                        "root_shape": _root_shape(root.annotation),
                    }
                else:
                    fields = {}
                    for attribute, info in obj.model_fields.items():
                        fields[info.alias or attribute] = {
                            "attribute": attribute,
                            "required": bool(info.is_required()),
                            "annotation": _annotation(info.annotation),
                            "literal": _literal_values(info.annotation),
                        }
                    record = {"kind": "model", "fields": fields}
            else:
                continue
            ref = getattr(obj, "__adcp_schema__", None)
            record.update(
                module=module.__name__,
                name=name,
                file=relative,
                header_document=document,
                schema_ref=(
                    {"document": ref.document, "pointer": ref.pointer} if ref is not None else None
                ),
                bases=[b.__name__ for b in obj.__bases__],
                extra=str((getattr(obj, "model_config", None) or {}).get("extra") or ""),
            )
            record["identity"] = _identity(record)
            classes.append(record)

    Path(args.out).write_text(
        json.dumps({"package": args.package, "src": str(src), "modules": modules, "classes": classes},
                   indent=1, default=str),
        encoding="utf-8",
    )
    print(f"{len(classes)} classes in {len(modules)} modules -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
