"""The MECHANICAL aliases: one of theirs, one of ours, schemas EQUAL -- and their entries.

**A 1:1 STRUCTURAL MATCH OWES NO PER-ELEMENT READING, which is the whole reason this file
is short.**  Reading 10 as amended makes a shared-subject alias a PAIR and requires the
split to be "proved PER ELEMENT, never by a ratio" -- but that clause is about two
identities that DIFFER.  `survey/structural_signature.py`'s 1:1 bucket is the rows where
the canonical schemas are EQUAL, so there is no element that differs and nothing to argue
element by element: the whole structure agrees, and the alias follows with no judgment
exercised.  What remains owed is the ENTRY, because reading 10 grades the pair:

    **AN ALIAS WHOSE ENTRY IS MISSING IS A READING 10 FAILURE AND NOT PARTIAL CREDIT**,
    because an undisclosed substitution is the exact defect this reading refused, arriving
    with our name on it instead of theirs.

So this script writes BOTH HALVES FROM ONE ROW and cannot write one without the other.

**AND THE ENTRY'S SHAPE DEPENDS ON WHOSE WORD OUR TARGET IS.**  Reading 10: "NO ALIAS POINTS
AT A NAME THIS COMPILER MINTED FROM STRUCTURE ... UNLESS THE ALIAS IS UPSTREAM'S OWN
PUBLISHED WORD, DECLARED DEPRECATED AND PENDING ... the migration entry must say the word is
PROVISIONAL -- naming the untitled node by pointer and the upstream ask that would title it."
Every word on the left of every row here IS upstream's own published word, so the narrowed
clause applies throughout; what decides whether a row is PROVISIONAL is whether OUR word is
one the BUNDLE TITLES or one §4 derived from the structure.  That is read off the bundle's
own `title` vocabulary (`alias_surface.bundle_index`) and never guessed:

    TITLED      the bundle titles our word -- a plain alias, and the entry names both
                spellings and the pointer the document states the subject at.
    PROVISIONAL the bundle titles nothing at that node, so our word is minted from the
                parent and the key -- the alias RECORDS upstream's commitment, the entry
                says PROVISIONAL and names the pointer and the ask.

**A WORD TWO ROWS DISAGREE ABOUT GETS NO ALIAS.**  Reading 10: "a name resolves to a
DIFFERENT class of ours depending on which upstream module the import came from, so one flat
alias cannot serve both."  One flat namespace cannot hold two meanings for one word, so such
a word is reported and takes a migration note instead -- never an arbitrary pick.

Run::

    PYTHONPATH=.:src ./.venv/bin/python survey/mechanical_aliases.py --report
    PYTHONPATH=.:src ./.venv/bin/python survey/mechanical_aliases.py --write
"""

from __future__ import annotations

import argparse
import collections
import csv
import importlib
import json
import pkgutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

MECHANICAL = HERE / "mechanical-9.6.1.tsv"
COMPAT = ROOT / "src" / "adcp" / "types" / "compat.py"
GUIDE = ROOT / "docs" / "migration-from-upstream.md"
BUNDLE = ROOT / "schemas" / "cache" / "3.2"

#: The heading this script owns in the guide, and the fence it writes between.  Rewritten
#: whole on every run, so the generated half of the guide can never drift from the aliases.
SECTION = "## §10. The mechanical 1:1 structural aliases"
FENCE = "<!-- GENERATED by survey/mechanical_aliases.py -- do not edit between the fences -->"
END = "<!-- END GENERATED -->"


def public_surface() -> dict[int, list[str]]:
    """``id(object)`` -> every ``adcp.types.<domain>.<Word>`` path that re-exports it.

    **AN ALIAS MUST POINT AT A PUBLIC NAME OF OURS, and `_schemas` is not one.**  The 1:1
    table records the DECLARING module, which is private by §1's design ("a generated class
    can change without disturbing what an application imports").  Reading 6 is what makes a
    declaration reachable, and a row whose target reaches no domain module is reported as
    owing an EXPORT -- which is §4's own remedy, "an EXPORT or a NAME, never a split" -- and
    never bound here.
    """
    types_package = importlib.import_module("adcp.types")
    out: dict[int, list[str]] = collections.defaultdict(list)
    for found in pkgutil.iter_modules(types_package.__path__, "adcp.types."):
        leaf = found.name.rsplit(".", 1)[1]
        if leaf.startswith("_") or leaf == "compat":
            continue
        try:
            module = importlib.import_module(found.name)
        except Exception:  # noqa: BLE001 -- a module that does not import is its own defect
            continue
        for word in getattr(module, "__all__", ()) or ():
            out[id(getattr(module, word))].append(f"{found.name}.{word}")
    return out


def already_bound() -> set[str]:
    """Every flat spelling that resolves today, read off the alias module itself.

    Read by IMPORT and not by a regex over the file, because the question is what
    ``from adcp.types import X`` does -- `__all__` plus `__adcp_flat_only__` is exactly the
    set `adcp.types.__getattr__` answers, and that function is the authority.
    """
    compat = importlib.import_module("adcp.types.compat")
    return {*compat.__all__, *compat.__adcp_flat_only__}


def rows() -> list[dict[str, str]]:
    with MECHANICAL.open(encoding="utf-8") as handle:
        body = [line for line in handle if not line.startswith("#")]
    return list(csv.DictReader(body, delimiter="\t"))


def decide() -> dict[str, object]:
    """One verdict per upstream NAME, with the reason, and never a pick between two."""
    import alias_surface

    index = alias_surface.bundle_index(BUNDLE)
    titles = index["titles"]
    surface = public_surface()
    bound = already_bound()

    proposals: dict[str, list[dict[str, str]]] = collections.defaultdict(list)
    needs_export: list[dict[str, str]] = []
    for row in rows():
        module, _, word = row["ours_declared_at"].rpartition(".")
        try:
            obj = getattr(importlib.import_module(module), word)
        except Exception as error:  # noqa: BLE001 -- recorded, never swallowed
            needs_export.append({**row, "why": f"{type(error).__name__}: {error}"})
            continue
        paths = surface.get(id(obj))
        if not paths:
            needs_export.append({**row, "why": "reaches no adcp.types.<domain> export"})
            continue
        record = getattr(obj, "__adcp_schema__", None)
        for name in row["upstream_names"].split():
            proposals[name].append(
                {
                    "ours": sorted(paths)[0],
                    "word": word,
                    "theirs_declared_at": row["theirs_declared_at"],
                    "signature": row["signature"],
                    "method": row["method"],
                    "document": record.document if record is not None else "",
                    "pointer": record.pointer if record is not None else "",
                }
            )

    pairs: list[dict[str, str]] = []
    disagree: dict[str, list[str]] = {}
    present: list[str] = []
    for name, candidates in sorted(proposals.items()):
        distinct = sorted({candidate["ours"] for candidate in candidates})
        if len(distinct) > 1:
            disagree[name] = distinct
            continue
        if name in bound:
            present.append(name)
            continue
        entry = candidates[0]
        titled = entry["word"].lower() in titles
        pairs.append(
            {
                **entry,
                "name": name,
                "verdict": "TITLED" if titled else "PROVISIONAL",
                "node": f"{entry['document']}#{entry['pointer']}" if entry["document"] else "",
            }
        )
    return {
        "pairs": pairs,
        "name_resolves_to_two_of_ours": disagree,
        "already_resolves_flat": present,
        "target_owes_an_export": needs_export,
        "declarations": len(rows()),
    }


def alias_block(pairs: list[dict[str, str]]) -> str:
    lines = []
    for pair in pairs:
        module, _, word = pair["ours"].rpartition(".")
        lines.append(f"from {module} import {word} as {pair['name']}")
    return "\n".join(sorted(lines))


def guide_section(pairs: list[dict[str, str]], report: dict[str, object]) -> str:
    provisional = [pair for pair in pairs if pair["verdict"] == "PROVISIONAL"]
    titled = [pair for pair in pairs if pair["verdict"] == "TITLED"]
    head = f"""{SECTION}

**Every row below is a PAIR, and the pair is the unit** — `docs/plan/final-state.md` reading
10: "an alias whose entry is missing is a reading 10 FAILURE and not partial credit, because
an undisclosed substitution is the exact defect this reading refused, arriving with our name
on it instead of theirs."

**WHAT MAKES THESE ROWS MECHANICAL IS THAT NOTHING WAS DECIDED.**
`survey/structural_signature.py` compares the two sides by the class's own **resolved JSON
schema** — the wire names, the optionality, the defaults, the discriminators and the
constraint keywords, canonicalised by the normalisations that file states with its reason for
each. A row is here only when the two schemas are **EQUAL**. Reading 10's "the split is
proved PER ELEMENT, never by a ratio" is the rule for identities that *differ*; here no
element differs, so there is no element to argue and no judgment was exercised. A reader who
distrusts a row distrusts a normalisation, and every one of them is named in
`survey/mechanical-9.6.1.tsv`'s own header.

**{len(pairs)} pairs**, from the {report["declarations"]} 1:1 declarations the instrument
found against upstream 9.6.1 — the remainder of that bucket already resolved flat
({len(report["already_resolves_flat"])} names) or is withheld for a reason stated below.

**{len(titled)} rows are plain and {len(provisional)} are PROVISIONAL**, and the difference
is whose word *ours* is. Upstream's word, on the left, is always theirs — that is what makes
the narrowed clause apply at all. Where the bundle **titles** our word the row is plain; where
it titles nothing at that node our word is derived from the parent and the key, so the alias
*records* upstream's commitment rather than minting one and **the row says PROVISIONAL**. The
upstream ask is the same sentence in every provisional row and is stated once here rather than
{len(provisional)} times: **give the node at that pointer a `title`.** Upstream's generator
derives its word from the parent and the key exactly as this package does, so neither side is
choosing it and only the bundle can settle it.

| upstream's word | our surface name | the node the document states it at | status |
|---|---|---|---|
"""
    body = "".join(
        f"| `{pair['name']}` | `{pair['ours']}` | `{pair['node'] or '—'}` | {pair['verdict']} |\n"
        for pair in pairs
    )
    tail = f"""
**WHAT IS WITHHELD, AND WHY — counted, not omitted.**

* **{len(report["name_resolves_to_two_of_ours"])} words reach two different declarations of
  ours** depending on which module of upstream's the import came from. Reading 10: "a name
  resolves to a *different* class of ours depending on which upstream module the import came
  from, so one flat alias cannot serve both." One flat namespace cannot hold two meanings for
  one word, so these take a migration note and no alias — and the alternative on offer is an
  arbitrary pick, which is the silent substitution this reading exists to refuse.
* **{len(report["target_owes_an_export"])} declarations of ours reach no
  `adcp.types.<domain>` export.** §4's own remedy applies and it is not this layer's: "an
  EXPORT or a NAME, never a split. The alias layer cannot reach a private name."

Both lists are re-derivable with `survey/mechanical_aliases.py --report`, which prints them
by name.
"""
    return head + body + tail


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--json", type=Path)
    args = parser.parse_args()

    report = decide()
    pairs: list[dict[str, str]] = report["pairs"]  # type: ignore[assignment]
    print(f"1:1 declarations           {report['declarations']}")
    print(f"PAIRS to write             {len(pairs)}")
    print(f"  TITLED                   {sum(1 for p in pairs if p['verdict'] == 'TITLED')}")
    print(f"  PROVISIONAL              {sum(1 for p in pairs if p['verdict'] == 'PROVISIONAL')}")
    print(f"already resolves flat      {len(report['already_resolves_flat'])}")
    print(f"name -> two of ours        {len(report['name_resolves_to_two_of_ours'])}")
    print(f"target owes an export      {len(report['target_owes_an_export'])}")
    if args.json:
        args.json.write_text(json.dumps(report, indent=1, default=str))
    if args.report:
        for name, where in sorted(report["name_resolves_to_two_of_ours"].items()):  # type: ignore[union-attr]
            print(f"  TWO-OF-OURS {name}: {' | '.join(where)}")
        for row in report["target_owes_an_export"]:  # type: ignore[union-attr]
            print(f"  OWES-EXPORT {row['ours_declared_at']}: {row['why']}")
    if not args.write:
        return

    # ---- compat.py: the statements, `__all__`, and the provisional mapping -----------
    text = COMPAT.read_text(encoding="utf-8")
    lines = text.splitlines()
    imports = [i for i, line in enumerate(lines) if line.startswith("from adcp.types")]
    block = sorted({*(lines[i] for i in imports), *alias_block(pairs).splitlines()})
    lines = lines[: imports[0]] + block + lines[imports[-1] + 1 :]
    text = "\n".join(lines) + "\n"

    start = text.index("__all__ = [")
    stop = text.index("\n]", start)
    words = sorted(
        {*(w.strip().strip('",') for w in text[start:stop].splitlines() if w.strip().startswith('"')),
         *(pair["name"] for pair in pairs)}
    )
    text = text[:start] + "__all__ = [\n" + "".join(f'    "{w}",\n' for w in words) + text[stop + 1 :]

    start = text.index("__adcp_provisional__ = {")
    stop = text.index("\n}", start)
    existing = dict(
        line.strip().rstrip(",").split(": ", 1)
        for line in text[start:stop].splitlines()
        if line.strip().startswith('"')
    )
    existing.update(
        {f'"{pair["name"]}"': f'"{pair["node"]}"'
         for pair in pairs if pair["verdict"] == "PROVISIONAL"}
    )
    body = "".join(f"    {k}: {v},\n" for k, v in sorted(existing.items()))
    text = text[:start] + "__adcp_provisional__ = {\n" + body + text[stop + 1 :]
    COMPAT.write_text(text, encoding="utf-8")
    print(f"compat.py: {len(block)} alias statements, {len(words)} words, "
          f"{len(existing)} provisional")

    # ---- the guide: the other half of every pair --------------------------------------
    guide = GUIDE.read_text(encoding="utf-8")
    section = FENCE + "\n\n" + guide_section(pairs, report) + "\n" + END
    if FENCE in guide:
        head, _, rest = guide.partition(FENCE)
        _, _, tail = rest.partition(END)
        guide = head + section + tail
    else:
        marker = "\n---\n\n## Re-deriving this document"
        head, _, tail = guide.partition(marker)
        guide = head + "\n---\n\n" + section + "\n" + marker.lstrip("\n") + tail
    GUIDE.write_text(guide, encoding="utf-8")
    print(f"{GUIDE.name}: §10 rewritten with {len(pairs)} pairs")


if __name__ == "__main__":
    main()
