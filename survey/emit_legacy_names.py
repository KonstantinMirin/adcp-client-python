"""Write ``src/adcp/types/legacy_names.py`` from the N:1 table. One alias per name of theirs.

Reads ``survey/name-table-9.6.1.json`` -- ``survey/name_table.py``'s output, every row already
resolved by one of its nine rules -- and emits a re-export for each. It decides nothing and
holds no rule; the table is the decision and this is the rendering.

**N OF THEIR NAMES POINT AT ONE OF OURS, AND THAT IS THE WHOLE SHAPE.** Upstream's tree holds
3,226 classes and ours 2,500 because they emit per POSITION and we emit per SUBJECT, so a
subject reached from sixteen positions has sixteen of their names and one of ours. Every one of
those sixteen gets an alias and they all point at the same object.

**A NAME ALREADY SERVED IS SKIPPED, not re-bound.** The facade consults this module LAST, after
``compat``, the flat-only table, ``_adapter``, ``_restored`` and ``_flat``, so a name any of
them answers for is never reached here -- but emitting it anyway would put a second statement
about one word in the tree, and the import would be dead text a reader has to reconcile. The
skip is counted and reported.
"""

from __future__ import annotations

import collections
import json
import pathlib
import sys

import name_table

TABLE = pathlib.Path("survey/name-table-9.6.1.json")
OUT = pathlib.Path("src/adcp/types/legacy_names.py")

DOC = '''"""Upstream's published class names, bound to the class of ours denoting one subject.

**GENERATED by ``survey/emit_legacy_names.py`` from ``survey/name-table-9.6.1.json``.**

WHAT THIS IS, and it is only one thing: a NAME. Upstream's 9.6.1 wheel published a word; our
compiler names the same subject from its document and arrives at another. This module binds
theirs to ours so code written against their wheel keeps importing. It declares no class and
changes no accepted set -- an alias is a second spelling of one object.

**THE RELATION IS N:1.** They emit a class per POSITION, we emit one per SUBJECT (architecture
§3a), so a subject reached from several positions carries several of their names and one of
ours: sixteen of their names resolve to ``SIComponentCatalog``, eleven to
``VerifyBrandClaimsRequestBulk``. Every one of them is bound here and they all point at the
same object, which is why ``isinstance`` holds across all of them.

EVERY ROW WAS RESOLVED BY A RULE AND NEVER BY EYE -- ``survey/name_table.py`` carries the nine
and the count each decided. None of them compares two class definitions side by side, which is
what ``docs/plan/final-state.md`` reading 10 forbids.

**ONE ROW IS ASSERTED AND NOT DERIVED, AND IT IS MARKED.** A row whose comment reads ``the
subject this word now denotes`` is a binding of a WORD'S TARGET: not "upstream's name,
renamed", but upstream's word bound to the subject the owner says that word denotes.
``survey/name_table.ASSERTED`` is the one place such a binding is stated, with its reason.

It is not a redirect. ``Format`` denoted ``core/format.json``'s v1 named-format definition
here before; it denotes the canonical ``format_kind`` + ``params`` declaration now, which is
what upstream's own runtime means by the word. Code that said ``Format`` and meant v1 receives
the canonical declaration and is REFUSED at validation by the document's own schema, loudly, at
the first value that distinguishes the two subjects. ``docs/migration-from-upstream.md`` says
why and what to import instead -- the v1 definition is ``LegacyFormat``.
"""'''


def main() -> int:
    table = json.loads(TABLE.read_text())
    #: **THE ASSERTED BINDINGS, OVERLAID BEFORE ANYTHING IS RENDERED**
    #: (``survey/name_table.ASSERTED``, ``adcp-client-python-8wd8``).  This module still
    #: holds no rule: ``name_table`` is where the nine derivations and the one asserted
    #: table both live, and ``applied`` is the one way the assertion reaches a rendering.
    #:
    #: **A WORD'S TARGET IS A DIFFERENT KIND OF ROW FROM A DERIVATION, which is why it is
    #: declared rather than computed.**  The nine rules are facts about two trees -- a
    #: shared module path, a field set, a branch index, a shared word.  ``Format`` is
    #: neither: ``cross-name`` used to resolve it by finding the one class of ours
    #: carrying that word, and after ``codegen/overrides.py`` renamed that class
    #: ``LegacyFormat`` no class of ours carries it, so there is nothing to find.  The
    #: word has not gone away; its SUBJECT moved, and only a decision says where to.
    rows, moved = name_table.applied(table["rows"])
    for their, was, now in moved:
        print(
            f"asserted {their}: {was or '(no derived row)'} -> {now}",
            file=sys.stderr,
        )

    # **THE "ALREADY SERVED" QUESTION MUST NOT SEE THIS MODULE'S OWN PREVIOUS OUTPUT.**  The
    # facade consults `legacy_names` last, so importing `adcp.types` with a populated
    # `legacy_names.py` on disk answers True for every word the LAST run bound -- and the
    # emitter then reports its own file as almost entirely redundant.  Measured: 1,802 of
    # 1,817 words read as served that way.  So the file is reduced to a stub BEFORE the
    # surface is imported, and the question is asked of the layers below it only.
    import importlib

    OUT.write_text('"""Placeholder; rewritten below."""\n')
    sys.path.insert(0, "src")
    surface = importlib.import_module("adcp.types")

    # **GROUP BY THEIR NAME FIRST, because the N:1 RUNS BOTH WAYS.**  Several of their names
    # denote one subject of ours -- that is the fan-out this module exists to serve.  But the
    # same WORD also appears in several of their modules, because they emit per position, and
    # those positions can be different subjects: their `Accessibility` in one document is not
    # their `Accessibility` in another.  A flat surface has one slot per word, so a word whose
    # rows disagree about the target is AMBIGUOUS and is DECLINED -- bound last-wins it would
    # answer with whichever row the sort happened to put last, which is the defect
    # `adcp.types.__init__` records as "core.Status meaning one of fourteen things".
    targets: dict[str, set[str]] = collections.defaultdict(set)
    #: Which words were ASSERTED rather than derived, so the statement can say so.  Read
    #: off the row's own ``how`` and not off ``name_table.ASSERTED`` again: one reading.
    said = {row["their"] for row in rows if row.get("how") == "asserted"}
    for row in rows:
        targets[row["their"]].add(row["ours"])

    by_target: dict[str, list[str]] = collections.defaultdict(list)
    served = ambiguous = 0
    declined: dict[str, list[str]] = {}
    for name, where in sorted(targets.items()):
        if hasattr(surface, name):
            served += 1
            continue
        if len(where) > 1:
            ambiguous += 1
            declined[name] = sorted(where)
            continue
        by_target[next(iter(where))].append(name)

    imports: list[str] = []
    bound: list[str] = []
    unimportable: list[str] = []
    for target in sorted(by_target):
        module, _, symbol = target.rpartition(".")
        # **A TARGET THAT IS NOT AN IMPORTABLE NAME IS NOT AN ALIAS.**  `points_at` is read off
        # an object's `__module__` and `__qualname__`, and a parametrised generic answers
        # `AdCPRootModel[Any]` -- a type expression, not a binding.  `from ... import
        # AdCPRootModel[Any]` is a SyntaxError that takes the whole module with it, so such a
        # target is skipped and counted rather than written.
        if not symbol.isidentifier() or not all(
            part.isidentifier() for part in module.split(".")
        ):
            unimportable.extend(by_target[target])
            continue
        # **AND NEVER A TARGET INSIDE THIS MODULE.**  The binding dump the table is built from
        # is taken on a tree where this file already exists, so a word bound by the LAST run
        # appears as one of our own bindings and can be chosen as a target -- which emits
        # `from adcp.types.legacy_names import X as X` and raises ImportError on a partially
        # initialised module.  It is the same defect as the "already served" check reading this
        # module's own output, one layer along.
        if module == "adcp.types.legacy_names":
            unimportable.extend(by_target[target])
            continue
        for name in sorted(set(by_target[target])):
            stmt = f"from {module} import {symbol} as {name}"
            # The casing of a name is UPSTREAM'S and is not ours to correct: they publish
            # lowercase words for classes and mixed-case words for constants, and an alias
            # that renamed them would answer no caller.  So the convention rules are
            # annotated per statement, derived from the two spellings rather than listed.
            flags = []
            if len(stmt) > 100:
                flags.append("E501")
            if name.isupper() and not symbol.isupper():
                flags.append("N814")
            if symbol.isupper() and not name.isupper():
                flags.append("N811")
            if symbol[:1].isupper() and name[:1].islower():
                flags.append("N813")
            if flags:
                stmt += f"  # noqa: {', '.join(flags)} -- upstream published this spelling"
            #: **AN ASSERTED ROW SAYS SO IN THE FILE** (``adcp-client-python-8wd8``).  Every
            #: other statement here is a derivation a rule reached; this one is a decision,
            #: and a reader has to be able to tell them apart without going to the table.
            #: The wording is deliberate -- not "renamed", which would describe a redirect,
            #: but the subject the word now DENOTES.
            if name in said:
                stmt += (
                    ""
                    if "# noqa" in stmt
                    else "  #"
                ) + f"  {name}: the subject this word now denotes (name_table.ASSERTED)"
            imports.append(stmt)
            bound.append(name)

    lines = [DOC, "", "from __future__ import annotations", ""]
    lines += sorted(imports)
    lines += ["", "__all__ = ["]
    lines += [f'    "{name}",' for name in sorted(set(bound))]
    lines += ["]", ""]
    OUT.write_text("\n".join(lines))

    fan = {t: len(set(n)) for t, n in by_target.items()}
    many = sorted(((n, t) for t, n in fan.items() if n > 1), reverse=True)
    if declined:
        lines += ["", "#: Words whose rows disagree about the subject -- DECLINED, never"]
        lines += ["#: last-wins.  Each is reachable at its own domain path."]
        lines += ["__adcp_ambiguous__ = {"]
        for name in sorted(declined):
            lines.append(f'    "{name}": [')
            for where in declined[name]:
                lines.append(f'        "{where}",')
            lines.append("    ],")
        lines += ["}", ""]
        OUT.write_text("\n".join(lines))
    if unimportable:
        print(f"  target not importable: {len(set(unimportable))} (a type expression, not a name)")
    print(f"table rows            : {len(rows)}")
    print(f"  distinct words      : {len(targets)}")
    print(f"  AMBIGUOUS, declined : {ambiguous}")
    print(f"  already served above: {served}")
    print(f"  aliases emitted     : {len(set(bound))}")
    print(f"  distinct targets    : {len(by_target)}")
    print(f"  targets taking several of their names: {len(many)}")
    for n, t in many[:5]:
        print(f"      {n:3d} -> {t.split('.')[-1]}")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
